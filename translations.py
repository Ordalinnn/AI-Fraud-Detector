def validate_translations():
    """Raises ValueError listing exactly which language is missing which
    key(s), if the three language dicts above don't all have identical key
    sets. Called at import time (bottom of this file) so a missing
    translation is caught immediately on app startup / test collection,
    not silently as a KeyError the first time a user picks that language."""
    key_sets = {lang: set(d.keys()) for lang, d in TEXT.items()}
    all_keys = set.union(*key_sets.values())
    problems = []
    for lang, keys in key_sets.items():
        missing = all_keys - keys
        if missing:
            problems.append(f"{lang} is missing: {sorted(missing)}")
    if problems:
        raise ValueError("Translation key mismatch between languages:\n" + "\n".join(problems))


def get_translations(lang):
    """Returns the translation dict for `lang`, falling back to
    DEFAULT_LANG if `lang` isn't recognized (defensive — app.py already
    normalizes/validates lang against LANG_OPTIONS before this is called)."""
    return TEXT.get(lang, TEXT[DEFAULT_LANG])


