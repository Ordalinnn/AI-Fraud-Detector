"""
Exports the on-device model for the Android app (android/) and proves the
app's re-implementation computes the same probabilities as scikit-learn.

    python scripts/export_mobile_model.py

Which model: the character n-gram + logistic regression member of the web
app's ensemble - the strongest single model (93.6% on the jury's 282-message
test, vs 94.7% for the full ensemble) and the only one that is tiny, has no
hand-written keyword lists to port, and needs nothing but arithmetic to run.
Vocabulary is capped at 20,000 n-grams (same test accuracy as uncapped,
~0.9 MB file). Trained on the same data as the web app: the 1,398
hand-written examples + 400 real UCI SMS.

Writes:
  android/app/src/main/assets/char_model.tsv   the model
  browser-extension/char_model.tsv             the same file for the browser
                                               extension (scorer.js)
  android/app/src/test/resources/golden.tsv    texts + sklearn probabilities;
                                               the Kotlin unit test must match
  reports/mobile_model.json                    accuracy of exactly this model

The Python `reference_proba` below is a line-by-line spec of what
FraudScorer.kt does; this script fails if it disagrees with sklearn.
"""
from __future__ import annotations

import json
import math
import sys
from collections import Counter
from pathlib import Path

import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import GroupShuffleSplit
from sklearn.pipeline import Pipeline

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import fraud_eval as fe  # noqa: E402
import fraud_model as fm  # noqa: E402

MAX_FEATURES = 20_000
MODEL_PATH = ROOT / "android" / "app" / "src" / "main" / "assets" / "char_model.tsv"
GOLDEN_PATH = ROOT / "android" / "app" / "src" / "test" / "resources" / "golden.tsv"
EXTENSION_MODEL_PATH = ROOT / "browser-extension" / "char_model.tsv"
REPORT_PATH = ROOT / "reports" / "mobile_model.json"

# Python's str.split() whitespace set (FraudScorer.kt uses the same list).
PY_WHITESPACE = set("\t\n\x0b\x0c\r\x1c\x1d\x1e\x1f \x85\xa0\u1680\u2028\u2029\u202f\u205f\u3000") | {
    chr(c) for c in range(0x2000, 0x200B)}


def build_pipeline():
    return Pipeline([
        ("tfidf", TfidfVectorizer(analyzer="char_wb", ngram_range=fm.CHAR_NGRAM_RANGE, min_df=fm.CHAR_MIN_DF,
                                  sublinear_tf=True, lowercase=True, max_features=MAX_FEATURES)),
        ("clf", LogisticRegression(C=fm.CHAR_C, max_iter=2000, random_state=fm.MODEL_RANDOM_STATE)),
    ])


# ---------- the spec FraudScorer.kt implements ----------

def char_wb_ngrams(text: str, n_min: int, n_max: int) -> list[str]:
    words, cur = [], []
    for ch in text.lower():
        if ch in PY_WHITESPACE:
            if cur:
                words.append("".join(cur))
                cur = []
        else:
            cur.append(ch)
    if cur:
        words.append("".join(cur))
    out = []
    for w in words:
        w = " " + w + " "
        for n in range(n_min, n_max + 1):
            offset = 0
            out.append(w[offset:offset + n])
            while offset + n < len(w):
                offset += 1
                out.append(w[offset:offset + n])
            if offset == 0:
                break
    return out


def reference_proba(text: str, model: dict) -> float:
    counts = Counter(g for g in char_wb_ngrams(text, model["n_min"], model["n_max"]) if g in model["vocab"])
    dot, sq = 0.0, 0.0
    for g, c in counts.items():
        idf, coef = model["vocab"][g]
        w = (1.0 + math.log(c)) * idf
        dot += w * coef
        sq += w * w
    z = model["intercept"] + (dot / math.sqrt(sq) if sq > 0 else 0.0)
    return 1.0 / (1.0 + math.exp(-z))


# ---------- export ----------

def write_model(pipe, path: Path) -> dict:
    tf, clf = pipe.named_steps["tfidf"], pipe.named_steps["clf"]
    coef = clf.coef_[0]
    vocab = {g: (float(tf.idf_[i]), float(coef[i])) for g, i in tf.vocabulary_.items()}
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# AI Fraud Detector on-device model: char_wb n-grams + logistic regression",
             "# generated by scripts/export_mobile_model.py - do not edit",
             f"intercept\t{float(clf.intercept_[0])!r}",
             f"ngram_range\t{fm.CHAR_NGRAM_RANGE[0]}\t{fm.CHAR_NGRAM_RANGE[1]}"]
    for g in sorted(vocab):
        idf, c = vocab[g]
        assert "\t" not in g and "\n" not in g
        lines.append(f"{g}\t{idf!r}\t{c!r}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"vocab": vocab, "intercept": float(clf.intercept_[0]),
            "n_min": fm.CHAR_NGRAM_RANGE[0], "n_max": fm.CHAR_NGRAM_RANGE[1]}


def main():
    df = fe.load_dataset()
    real = fm.load_real_training_sample()
    hold = fm.load_real_holdout()
    y = df["label"].to_numpy()
    groups = fm.template_groups(df["text"].tolist())

    # 1) honest accuracy of exactly this model on the jury's split
    tr, te = next(GroupShuffleSplit(n_splits=1, test_size=fm.EVAL_TEST_SIZE,
                                    random_state=fm.MODEL_RANDOM_STATE).split(df, y, groups))
    texts_tr = [df["text"].iloc[i] for i in tr] + [t for t, _ in real]
    y_tr = np.concatenate([y[tr], [label for _, label in real]])
    eval_pipe = build_pipeline().fit(texts_tr, y_tr)
    p_te = eval_pipe.predict_proba([df["text"].iloc[i] for i in te])[:, 1]
    report = {"max_features": MAX_FEATURES, "jury_test": {}}
    for thr in (0.5, 0.8, 0.95):
        m = fe.metrics(y[te], p_te, threshold=thr)
        report["jury_test"][str(thr)] = {k: (round(v, 4) if isinstance(v, float) else v)
                                         for k, v in m.items() if k in ("TN", "FP", "FN", "TP", "accuracy", "recall", "fpr")}

    # 2) the shipped model: everything the web app trains on
    all_texts = df["text"].tolist() + [t for t, _ in real]
    all_y = np.concatenate([y, [label for _, label in real]])
    pipe = build_pipeline().fit(all_texts, all_y)
    model = write_model(pipe, MODEL_PATH)
    EXTENSION_MODEL_PATH.write_bytes(MODEL_PATH.read_bytes())

    ph = pipe.predict_proba(hold["text"].tolist())[:, 1]
    ham = hold["label"].to_numpy() == 0
    report["real_holdout_trained_on_full"] = {
        str(thr): {"false_alarms_on_real_legit": round(float((ph[ham] >= thr).mean()), 4),
                   "flagged_real_spam": round(float((ph[~ham] >= thr).mean()), 4)}
        for thr in (0.5, 0.8, 0.95)}

    # 3) the reference implementation must equal sklearn on many texts,
    #    including Kazakh, emoji (astral code points), NBSP and odd spacing
    tricky = ["", "   ", "😀 Ваша карта заблокирована 😀", "Сіздің\u00a0картаңыз\u2003бұғатталды!!",
              "КОД   из\tSMS\n\nhttp://kaspi-login.xyz", "İstanbul ÇAĞRI", "a", "ab",
              "Привет, урок перенесли на пятницу", "URGENT!!! send OTP now http://bit.ly/x"]
    check = tricky + all_texts + hold["text"].tolist()
    skl = pipe.predict_proba(check)[:, 1]
    ref = np.array([reference_proba(t, model) for t in check])
    max_diff = float(np.max(np.abs(skl - ref)))
    report["reference_vs_sklearn_max_abs_diff"] = max_diff
    if max_diff > 1e-9:
        bad = int(np.argmax(np.abs(skl - ref)))
        raise SystemExit(f"reference implementation disagrees with sklearn by {max_diff} on {check[bad]!r}")

    # 4) golden vectors for the Kotlin unit test
    rng = np.random.default_rng(0)
    pick = tricky + [check[i] for i in rng.choice(len(check) - len(tricky), 400, replace=False) + len(tricky)]
    GOLDEN_PATH.parent.mkdir(parents=True, exist_ok=True)
    rows = ["# text<TAB>expected probability (sklearn); \\t \\n \\\\ escaped"]
    for t in pick:
        esc = t.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n").replace("\r", "\\r")
        rows.append(f"{esc}\t{float(pipe.predict_proba([t])[0, 1])!r}")
    GOLDEN_PATH.write_text("\n".join(rows) + "\n", encoding="utf-8")

    report["model_file_bytes"] = MODEL_PATH.stat().st_size
    report["n_ngrams"] = len(model["vocab"])
    REPORT_PATH.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
